export function AppProvider({ children }) {
    const [currentTab, setCurrentTab] = useState(() => {
        const hash = window.location.hash.replace('#', '');
        return ['map', 'species-audio', 'animals', 'tickets'].includes(hash) ? hash : 'map';
    });

    const [supportedLanguages, setSupportedLanguages] = useState(DEFAULT_LANGUAGES);
    const [currentLang, setCurrentLang] = useState(() => {
        try {
            const saved = localStorage.getItem(LANG_STORAGE_KEY);
            if (saved && translations[saved]) return saved;
        } catch (e) {}
        return 'vi';
    });
    const [remoteUiTranslations, setRemoteUiTranslations] = useState({});

    const [currentSession, setCurrentSession] = useState(null);

    const [isTicketModalOpen, setIsTicketModalOpen] = useState(false);
    const [isElectronicTicketModalOpen, setIsElectronicTicketModalOpen] = useState(false);
    const [selectedTicketForPass, setSelectedTicketForPass] = useState(null);
    const [selectedAnimalForDetail, setSelectedAnimalForDetail] = useState(null);
    const [isTranscriptModalOpen, setIsTranscriptModalOpen] = useState(false);

    const [audioState, setAudioState] = useState({
        animal: null,
        narration: null,
        isPlaying: false,
        isLoading: false,
        error: null,
        currentTime: 0,
        duration: 0,
        playbackRate: 1.0,
        volume: 1.0,
        isMuted: false,
        loadDurationMs: null,
        entityType: null,
        isVisible: false
    });

    const [navTargetAnimal, setNavTargetAnimal] = useState(null);
    const [filterZone, setFilterZone] = useState('all');
    const [toasts, setToasts] = useState([]);

    const showToast = useCallback((message, type = 'info') => {
        const id = Date.now() + Math.random();
        setToasts(prev => [...prev, { id, message, type }]);
        setTimeout(() => {
            setToasts(prev => prev.filter(t => t.id !== id));
        }, 3600);
    }, []);

    const removeToast = useCallback((id) => {
        setToasts(prev => prev.filter(t => t.id !== id));
    }, []);

    // Load active languages from Supabase API
    useEffect(() => {
        let isMounted = true;
        ZooApi.getLanguages().then(res => {
            if (isMounted && res.success && Array.isArray(res.data) && res.data.length > 0) {
                setSupportedLanguages(res.data);
            }
        });
        return () => { isMounted = false; };
    }, []);

    // Sync UI dictionary from Supabase CONTENT_TRANSLATIONS & document.title when currentLang changes
    useEffect(() => {
        if (typeof document !== 'undefined') {
            const localDict = translations[currentLang] || translations.en || translations.vi;
            if (localDict?.appTitle) {
                document.title = localDict.appTitle;
            }
        }
        let isMounted = true;
        ZooApi.getUiTranslations(currentLang).then(res => {
            if (isMounted && res.success && res.data && Object.keys(res.data).length > 0) {
                setRemoteUiTranslations(prev => ({
                    ...prev,
                    [currentLang]: res.data
                }));
            }
        });
        return () => { isMounted = false; };
    }, [currentLang]);

    // Load session on startup
    useEffect(() => {
        try {
            const raw = localStorage.getItem(STORAGE_KEY) || sessionStorage.getItem(STORAGE_KEY);
            if (raw) {
                const parsed = JSON.parse(raw);
                if (new Date(parsed.expiresAt) > new Date()) {
                    setCurrentSession(parsed);
                    if (parsed.sessionId) {
                        ZooApi.verifyTicketSession(parsed.sessionId).then(res => {
                            if (res && res.valid === false && !res.networkError) {
                                setCurrentSession(null);
                                localStorage.removeItem(STORAGE_KEY);
                                sessionStorage.removeItem(STORAGE_KEY);
                                showToast('Phiên tham quan đã hết hạn hoặc bị thu hồi bởi quản trị viên.', 'error');
                            }
                        });
                    }
                } else {
                    localStorage.removeItem(STORAGE_KEY);
                    sessionStorage.removeItem(STORAGE_KEY);
                }
            }
        } catch (e) {
            console.error('Error loading session:', e);
        }
    }, [showToast]);

    // Listen to window hash change
    useEffect(() => {
        const handleHashChange = () => {
            const hash = window.location.hash.replace('#', '') || 'map';
            if (['map', 'species-audio', 'animals', 'tickets'].includes(hash)) {
                setCurrentTab(hash);
            }
        };
        window.addEventListener('popstate', handleHashChange);
        return () => window.removeEventListener('popstate', handleHashChange);
    }, []);

    const switchTab = (tabId, updateHistory = true) => {
        setCurrentTab(tabId);
        if (updateHistory) {
            window.location.hash = `#${tabId}`;
        }
        window.scrollTo({ top: 0, behavior: 'smooth' });
    };

    const setLanguage = (lang) => {
        if (!lang) return;
        const normalized = lang.trim();
        setCurrentLang(normalized);
        try {
            localStorage.setItem(LANG_STORAGE_KEY, normalized);
        } catch (e) {}
        ZooApi.recordDashboardTelemetry({
            category: 'LANGUAGE',
            eventType: 'LANGUAGE_SELECTED',
            languageCode: normalized,
            sessionId: currentSession?.sessionId || null,
            targetType: 'Language',
            targetCode: normalized.toUpperCase(),
            targetName: `Ngôn ngữ ${normalized.toUpperCase()}`,
            triggerSource: 'MANUAL_UI',
            isSuccess: true
        });
        const baseT = translations[normalized] || translations.vi;
        const remoteT = remoteUiTranslations[normalized] || {};
        showToast(remoteT.languageChanged || baseT.languageChanged || `Language: ${normalized}`, 'info');
    };

    const validateTicketCode = async (code) => {
        const res = await ZooApi.validateTicket(code);
        if (res.success) {
            setCurrentSession(res.session);
            localStorage.setItem(STORAGE_KEY, JSON.stringify(res.session));
            setIsTicketModalOpen(false);
            showToast(res.message || 'Mở khóa phiên tham quan thành công!', 'success');
            return { success: true };
        }
        return { success: false, message: res.message };
    };

    const clearSession = () => {
        setCurrentSession(null);
        localStorage.removeItem(STORAGE_KEY);
        sessionStorage.removeItem(STORAGE_KEY);
        showToast('Đã kết thúc phiên tham quan', 'info');
    };

    const openElectronicTicketModal = (ticketData = null) => {
        setSelectedTicketForPass(ticketData);
        setIsElectronicTicketModalOpen(true);
    };

    const hasActiveSession = Boolean(currentSession);

    const checkTicketAccess = useCallback(() => {
        if (!currentSession || !currentSession.sessionId) {
            return {
                valid: false,
                reason: 'NO_TICKET',
                message: t?.ticketRequiredNarration || 'Bạn cần có vé tham quan hợp lệ để sử dụng chức năng thuyết minh.'
            };
        }
        if (new Date(currentSession.expiresAt) <= new Date()) {
            return {
                valid: false,
                reason: 'EXPIRED',
                message: t?.ticketExpiredNarration || 'Phiên tham quan của bạn đã hết hạn. Vui lòng mua vé mới để tiếp tục nghe thuyết minh.'
            };
        }
        return {
            valid: true,
            session: currentSession
        };
    }, [currentSession]);

    // Layered fallback: English base -> Vietnamese authoritative -> Target Language -> Remote DB overrides
    const mergedT = {
        ...(translations.en || {}),
        ...(translations.vi || {}),
        ...(translations[currentLang] || {}),
        ...(remoteUiTranslations[currentLang] || {})
    };

    return (
        <AppContext.Provider value={{
            currentTab,
            switchTab,
            currentLang,
            setLanguage,
            supportedLanguages,
            currentSession,
            hasActiveSession,
            checkTicketAccess,
            validateTicketCode,
            clearSession,
            isTicketModalOpen,
            setIsTicketModalOpen,
            isElectronicTicketModalOpen,
            setIsElectronicTicketModalOpen,
            selectedTicketForPass,
            setSelectedTicketForPass,
            openElectronicTicketModal,
            selectedAnimalForDetail,
            setSelectedAnimalForDetail,
            isTranscriptModalOpen,
            setIsTranscriptModalOpen,
            audioState,
            setAudioState,
            navTargetAnimal,
            setNavTargetAnimal,
            filterZone,
            setFilterZone,
            toasts,
            showToast,
            removeToast,
            t: mergedT
        }}>
            {children}
        </AppContext.Provider>
    );
}

export function useApp() {
    const context = useContext(AppContext);
    if (!context) {
        throw new Error('useApp must be used within an AppProvider');
    }
    return context;
}
