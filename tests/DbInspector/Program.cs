        if (File.Exists(envPath))
        {
            foreach (var line in File.ReadAllLines(envPath))
            {
                if (line.StartsWith("SUPABASE_CONNECTION_STRING="))
                {
                    pgConnStr = line.Substring("SUPABASE_CONNECTION_STRING=".Length).Trim();
                    break;
                }
            }
