/*
========================================================================================
 PROJECT: ZooGuide - Smart Multilingual Zoo Audio Tour Platform
 SCRIPT: ZooGuide_PostgreSQL.sql
 PURPOSE: PostgreSQL/Supabase database migration from the original SQL Server schema
 TARGET RDBMS: PostgreSQL (Supabase)
========================================================================================

IMPORTANT:
- This script is adapted from ZooGuide_Database.sql (SQL Server).
- It keeps the same 16 tables, relationships, constraints, indexes, and seed data.
- SQL Server-only syntax such as GO, USE, IDENTITY_INSERT, GETUTCDATE, NEWID,
  NVARCHAR(MAX), BIT, UNIQUEIDENTIFIER, DATEADD, ISNULL and dbo schema was converted.
- This script intentionally recreates tables. Run only on a fresh/test Supabase database,
  not on a database containing data you need to preserve.
========================================================================================
*/

CREATE EXTENSION IF NOT EXISTS pgcrypto;

-- ========================================================================================
-- 1. SAFE RESET FOR DEVELOPMENT
-- ========================================================================================

DROP TABLE IF EXISTS public."CHAT_MESSAGES" CASCADE;
DROP TABLE IF EXISTS public."CHAT_SESSIONS" CASCADE;
DROP TABLE IF EXISTS public."LOCATION_LOGS" CASCADE;
DROP TABLE IF EXISTS public."USER_LOYALTY" CASCADE;
DROP TABLE IF EXISTS public."MEMBERSHIP_LEVELS" CASCADE;
DROP TABLE IF EXISTS public."VISIT_HISTORY" CASCADE;
DROP TABLE IF EXISTS public."AUDIOS" CASCADE;
DROP TABLE IF EXISTS public."NARRATIONS" CASCADE;
DROP TABLE IF EXISTS public."ANIMALS" CASCADE;
DROP TABLE IF EXISTS public."AREAS" CASCADE;
DROP TABLE IF EXISTS public."SPECIES" CASCADE;
DROP TABLE IF EXISTS public."TICKET_SESSIONS" CASCADE;
DROP TABLE IF EXISTS public."TICKETS" CASCADE;
DROP TABLE IF EXISTS public."TICKET_TYPES" CASCADE;
DROP TABLE IF EXISTS public."LANGUAGES" CASCADE;
DROP TABLE IF EXISTS public."USERS" CASCADE;

-- ========================================================================================
-- 2. CORE TABLES
-- ========================================================================================

CREATE TABLE public."USERS" (
    "UserId" INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    "Username" VARCHAR(50) NOT NULL,
    "Email" VARCHAR(100) NOT NULL,
    "PasswordHash" VARCHAR(256) NOT NULL,
    "FullName" VARCHAR(100) NOT NULL,
    "Role" VARCHAR(20) NOT NULL,
    "Status" VARCHAR(20) NOT NULL,
    "CreatedAt" TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    "UpdatedAt" TIMESTAMPTZ NULL,
    "LastLoginAt" TIMESTAMPTZ NULL,
    "PasswordChangedAt" TIMESTAMPTZ NULL,

    CONSTRAINT "PK_USERS" PRIMARY KEY ("UserId"),
    CONSTRAINT "UQ_Users_Username" UNIQUE ("Username"),
    CONSTRAINT "UQ_Users_Email" UNIQUE ("Email"),
    CONSTRAINT "CK_Users_Role" CHECK ("Role" IN ('Visitor', 'Staff', 'Admin')),
    CONSTRAINT "CK_Users_Status" CHECK ("Status" IN ('Active', 'Locked'))
);

CREATE TABLE public."LANGUAGES" (
    "LanguageId" INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    "Code" VARCHAR(10) NOT NULL,
    "Name" VARCHAR(50) NOT NULL,
    "IsActive" BOOLEAN NOT NULL DEFAULT TRUE,
    "CreatedAt" TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    "UpdatedAt" TIMESTAMPTZ NULL,

    CONSTRAINT "PK_LANGUAGES" PRIMARY KEY ("LanguageId"),
    CONSTRAINT "UQ_Languages_Code" UNIQUE ("Code")
);

CREATE TABLE public."TICKET_TYPES" (
    "TicketTypeId" INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    "Name" VARCHAR(100) NOT NULL,
    "Description" VARCHAR(500) NULL,
    "Price" NUMERIC(18,2) NOT NULL,
    "DurationMinutes" INTEGER NOT NULL,
    "IsActive" BOOLEAN NOT NULL DEFAULT TRUE,
    "CreatedAt" TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    "UpdatedAt" TIMESTAMPTZ NULL,

    CONSTRAINT "PK_TICKET_TYPES" PRIMARY KEY ("TicketTypeId"),
    CONSTRAINT "CK_TicketTypes_Price" CHECK ("Price" >= 0),
    CONSTRAINT "CK_TicketTypes_Duration" CHECK ("DurationMinutes" > 0)
);

CREATE TABLE public."TICKETS" (
    "TicketId" INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    "TicketCode" VARCHAR(50) NOT NULL,
    "TicketTypeId" INTEGER NOT NULL,
    "IssuedAt" TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    "ValidFrom" TIMESTAMPTZ NOT NULL,
    "ValidUntil" TIMESTAMPTZ NOT NULL,
    "Status" VARCHAR(20) NOT NULL,
    "UsedAt" TIMESTAMPTZ NULL,
    "CreatedAt" TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    "UpdatedAt" TIMESTAMPTZ NULL,

    CONSTRAINT "PK_TICKETS" PRIMARY KEY ("TicketId"),
    CONSTRAINT "UQ_Tickets_TicketCode" UNIQUE ("TicketCode"),
    CONSTRAINT "FK_Tickets_TicketType" FOREIGN KEY ("TicketTypeId")
        REFERENCES public."TICKET_TYPES" ("TicketTypeId") ON DELETE NO ACTION,
    CONSTRAINT "CK_Tickets_Status" CHECK ("Status" IN ('Valid', 'Used', 'Expired', 'Cancelled', 'Locked')),
    CONSTRAINT "CK_Tickets_ValidDate" CHECK ("ValidUntil" >= "ValidFrom")
);

CREATE INDEX "IX_Tickets_TicketTypeId" ON public."TICKETS" ("TicketTypeId");
CREATE INDEX "IX_Tickets_Status" ON public."TICKETS" ("Status");

CREATE TABLE public."TICKET_SESSIONS" (
    "SessionId" UUID NOT NULL DEFAULT gen_random_uuid(),
    "TicketId" INTEGER NOT NULL,
    "UserId" INTEGER NULL,
    "StartedAt" TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    "ExpiredAt" TIMESTAMPTZ NOT NULL,
    "EndedAt" TIMESTAMPTZ NULL,
    "Status" VARCHAR(20) NOT NULL,
    "LastLatitude" NUMERIC(9,6) NULL,
    "LastLongitude" NUMERIC(9,6) NULL,
    "LastLocationAt" TIMESTAMPTZ NULL,

    CONSTRAINT "PK_TICKET_SESSIONS" PRIMARY KEY ("SessionId"),
    CONSTRAINT "FK_TicketSessions_Tickets" FOREIGN KEY ("TicketId")
        REFERENCES public."TICKETS" ("TicketId") ON DELETE NO ACTION,
    CONSTRAINT "FK_TicketSessions_Users" FOREIGN KEY ("UserId")
        REFERENCES public."USERS" ("UserId") ON DELETE SET NULL,
    CONSTRAINT "CK_TicketSessions_Status" CHECK ("Status" IN ('Active', 'Expired', 'Ended', 'Revoked')),
    CONSTRAINT "CK_TicketSessions_ExpiredAt" CHECK ("ExpiredAt" >= "StartedAt")
);

CREATE INDEX "IX_TicketSessions_TicketId" ON public."TICKET_SESSIONS" ("TicketId");
CREATE INDEX "IX_TicketSessions_UserId" ON public."TICKET_SESSIONS" ("UserId");
CREATE INDEX "IX_TicketSessions_Status" ON public."TICKET_SESSIONS" ("Status");
CREATE INDEX "IX_TicketSessions_TicketId_Status" ON public."TICKET_SESSIONS" ("TicketId", "Status");

CREATE TABLE public."SPECIES" (
    "SpeciesId" INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    "Name" VARCHAR(100) NOT NULL,
    "ScientificName" VARCHAR(150) NULL,
    "Description" VARCHAR(1000) NULL,
    "ConservationStatus" VARCHAR(50) NULL,
    "ImageUrl" VARCHAR(500) NULL,
    "CreatedAt" TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    "UpdatedAt" TIMESTAMPTZ NULL,

    CONSTRAINT "PK_SPECIES" PRIMARY KEY ("SpeciesId"),
    CONSTRAINT "UQ_Species_Name" UNIQUE ("Name")
);

CREATE TABLE public."AREAS" (
    "AreaId" INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    "Name" VARCHAR(100) NOT NULL,
    "Description" VARCHAR(1000) NULL,
    "Latitude" NUMERIC(9,6) NOT NULL,
    "Longitude" NUMERIC(9,6) NOT NULL,
    "RadiusMeters" NUMERIC(8,2) NOT NULL,
    "MapImageUrl" VARCHAR(500) NULL,
    "Status" VARCHAR(20) NOT NULL,
    "CreatedAt" TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    "UpdatedAt" TIMESTAMPTZ NULL,

    CONSTRAINT "PK_AREAS" PRIMARY KEY ("AreaId"),
    CONSTRAINT "UQ_Areas_Name" UNIQUE ("Name"),
    CONSTRAINT "CK_Areas_Radius" CHECK ("RadiusMeters" > 0),
    CONSTRAINT "CK_Areas_Status" CHECK ("Status" IN ('Active', 'Maintenance', 'Closed'))
);

CREATE TABLE public."ANIMALS" (
    "AnimalId" INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    "SpeciesId" INTEGER NOT NULL,
    "AreaId" INTEGER NOT NULL,
    "Name" VARCHAR(100) NOT NULL,
    "Description" VARCHAR(1000) NULL,
    "Gender" VARCHAR(10) NOT NULL,
    "DateOfBirth" DATE NULL,
    "Origin" VARCHAR(200) NULL,
    "HealthStatus" VARCHAR(200) NULL,
    "ConservationNote" VARCHAR(500) NULL,
    "ImageUrl" VARCHAR(500) NULL,
    "Status" VARCHAR(20) NOT NULL,
    "CreatedAt" TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    "UpdatedAt" TIMESTAMPTZ NULL,

    CONSTRAINT "PK_ANIMALS" PRIMARY KEY ("AnimalId"),
    CONSTRAINT "FK_Animals_Species" FOREIGN KEY ("SpeciesId")
        REFERENCES public."SPECIES" ("SpeciesId") ON DELETE NO ACTION,
    CONSTRAINT "FK_Animals_Areas" FOREIGN KEY ("AreaId")
        REFERENCES public."AREAS" ("AreaId") ON DELETE NO ACTION,
    CONSTRAINT "CK_Animals_Gender" CHECK ("Gender" IN ('Unknown', 'Male', 'Female')),
    CONSTRAINT "CK_Animals_Status" CHECK ("Status" IN ('Active', 'UnderTreatment', 'Transferred', 'Deceased'))
);

CREATE INDEX "IX_Animals_SpeciesId" ON public."ANIMALS" ("SpeciesId");
CREATE INDEX "IX_Animals_AreaId" ON public."ANIMALS" ("AreaId");
CREATE INDEX "IX_Animals_Status" ON public."ANIMALS" ("Status");

CREATE TABLE public."NARRATIONS" (
    "NarrationId" INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    "AnimalId" INTEGER NOT NULL,
    "LanguageId" INTEGER NOT NULL,
    "Title" VARCHAR(200) NOT NULL,
    "Content" TEXT NOT NULL,
    "AudioUrl" VARCHAR(500) NULL,
    "DurationSeconds" INTEGER NULL,
    "Status" VARCHAR(20) NOT NULL,
    "CreatedBy" INTEGER NOT NULL,
    "CreatedAt" TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    "UpdatedAt" TIMESTAMPTZ NULL,

    CONSTRAINT "PK_NARRATIONS" PRIMARY KEY ("NarrationId"),
    CONSTRAINT "UQ_Narrations_Animal_Language" UNIQUE ("AnimalId", "LanguageId"),
    CONSTRAINT "FK_Narrations_Animals" FOREIGN KEY ("AnimalId")
        REFERENCES public."ANIMALS" ("AnimalId") ON DELETE CASCADE,
    CONSTRAINT "FK_Narrations_Languages" FOREIGN KEY ("LanguageId")
        REFERENCES public."LANGUAGES" ("LanguageId") ON DELETE NO ACTION,
    CONSTRAINT "FK_Narrations_Users" FOREIGN KEY ("CreatedBy")
        REFERENCES public."USERS" ("UserId") ON DELETE NO ACTION,
    CONSTRAINT "CK_Narrations_Status" CHECK ("Status" IN ('Draft', 'Published', 'Archived'))
);

CREATE INDEX "IX_Narrations_LanguageId" ON public."NARRATIONS" ("LanguageId");
CREATE INDEX "IX_Narrations_CreatedBy" ON public."NARRATIONS" ("CreatedBy");

CREATE TABLE public."AUDIOS" (
    "AudioId" INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    "NarrationId" INTEGER NOT NULL,
    "FileUrl" VARCHAR(500) NOT NULL,
    "FileName" VARCHAR(255) NOT NULL,
    "MimeType" VARCHAR(100) NOT NULL DEFAULT 'audio/mpeg',
    "DurationSeconds" INTEGER NULL,
    "FileSize" BIGINT NULL,
    "Status" VARCHAR(20) NOT NULL,
    "CreatedAt" TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    "UpdatedAt" TIMESTAMPTZ NULL,

    CONSTRAINT "PK_AUDIOS" PRIMARY KEY ("AudioId"),
    CONSTRAINT "FK_Audios_Narrations" FOREIGN KEY ("NarrationId")
        REFERENCES public."NARRATIONS" ("NarrationId") ON DELETE CASCADE,
    CONSTRAINT "CK_Audios_Status" CHECK ("Status" IN ('Active', 'Inactive', 'Processing'))
);

CREATE INDEX "IX_Audios_NarrationId" ON public."AUDIOS" ("NarrationId");

CREATE TABLE public."VISIT_HISTORY" (
    "VisitId" INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    "UserId" INTEGER NOT NULL,
    "TicketId" INTEGER NOT NULL,
    "SessionId" UUID NOT NULL,
    "VisitedAt" TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT "PK_VISIT_HISTORY" PRIMARY KEY ("VisitId"),
    CONSTRAINT "FK_VisitHistory_Users" FOREIGN KEY ("UserId")
        REFERENCES public."USERS" ("UserId") ON DELETE NO ACTION,
    CONSTRAINT "FK_VisitHistory_Tickets" FOREIGN KEY ("TicketId")
        REFERENCES public."TICKETS" ("TicketId") ON DELETE NO ACTION,
    CONSTRAINT "FK_VisitHistory_Sessions" FOREIGN KEY ("SessionId")
        REFERENCES public."TICKET_SESSIONS" ("SessionId") ON DELETE NO ACTION
);

CREATE INDEX "IX_VisitHistory_UserId" ON public."VISIT_HISTORY" ("UserId");
CREATE INDEX "IX_VisitHistory_TicketId" ON public."VISIT_HISTORY" ("TicketId");
CREATE INDEX "IX_VisitHistory_SessionId" ON public."VISIT_HISTORY" ("SessionId");

-- ========================================================================================
-- 3. EXTENDED TABLES
-- ========================================================================================

CREATE TABLE public."LOCATION_LOGS" (
    "LocationLogId" BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    "SessionId" UUID NOT NULL,
    "Latitude" NUMERIC(9,6) NOT NULL,
    "Longitude" NUMERIC(9,6) NOT NULL,
    "Accuracy" NUMERIC(6,2) NULL,
    "RecordedAt" TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT "PK_LOCATION_LOGS" PRIMARY KEY ("LocationLogId"),
    CONSTRAINT "FK_LocationLogs_Sessions" FOREIGN KEY ("SessionId")
        REFERENCES public."TICKET_SESSIONS" ("SessionId") ON DELETE CASCADE
);

CREATE INDEX "IX_LocationLogs_SessionId_RecordedAt"
    ON public."LOCATION_LOGS" ("SessionId", "RecordedAt");

CREATE TABLE public."MEMBERSHIP_LEVELS" (
    "MembershipLevelId" INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    "Name" VARCHAR(50) NOT NULL,
    "MinPoints" INTEGER NOT NULL DEFAULT 0,
    "Description" VARCHAR(255) NULL,
    "IsActive" BOOLEAN NOT NULL DEFAULT TRUE,
    "CreatedAt" TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    "UpdatedAt" TIMESTAMPTZ NULL,

    CONSTRAINT "PK_MEMBERSHIP_LEVELS" PRIMARY KEY ("MembershipLevelId"),
    CONSTRAINT "UQ_MembershipLevels_Name" UNIQUE ("Name"),
    CONSTRAINT "CK_MembershipLevels_MinPoints" CHECK ("MinPoints" >= 0)
);

CREATE TABLE public."USER_LOYALTY" (
    "UserId" INTEGER NOT NULL,
    "Points" INTEGER NOT NULL DEFAULT 0,
    "MembershipLevelId" INTEGER NOT NULL,
    "UpdatedAt" TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT "PK_USER_LOYALTY" PRIMARY KEY ("UserId"),
    CONSTRAINT "FK_UserLoyalty_Users" FOREIGN KEY ("UserId")
        REFERENCES public."USERS" ("UserId") ON DELETE CASCADE,
    CONSTRAINT "FK_UserLoyalty_MembershipLevels" FOREIGN KEY ("MembershipLevelId")
        REFERENCES public."MEMBERSHIP_LEVELS" ("MembershipLevelId") ON DELETE NO ACTION,
    CONSTRAINT "CK_UserLoyalty_Points" CHECK ("Points" >= 0)
);

CREATE INDEX "IX_UserLoyalty_MembershipLevelId"
    ON public."USER_LOYALTY" ("MembershipLevelId");

CREATE TABLE public."CHAT_SESSIONS" (
    "ChatSessionId" UUID NOT NULL DEFAULT gen_random_uuid(),
    "SessionId" UUID NOT NULL,
    "CreatedAt" TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    "EndedAt" TIMESTAMPTZ NULL,

    CONSTRAINT "PK_CHAT_SESSIONS" PRIMARY KEY ("ChatSessionId"),
    CONSTRAINT "FK_ChatSessions_Sessions" FOREIGN KEY ("SessionId")
        REFERENCES public."TICKET_SESSIONS" ("SessionId") ON DELETE CASCADE
);

CREATE INDEX "IX_ChatSessions_SessionId"
    ON public."CHAT_SESSIONS" ("SessionId");

CREATE TABLE public."CHAT_MESSAGES" (
    "MessageId" BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    "ChatSessionId" UUID NOT NULL,
    "SenderType" VARCHAR(20) NOT NULL,
    "Content" TEXT NOT NULL,
    "CreatedAt" TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT "PK_CHAT_MESSAGES" PRIMARY KEY ("MessageId"),
    CONSTRAINT "FK_ChatMessages_Sessions" FOREIGN KEY ("ChatSessionId")
        REFERENCES public."CHAT_SESSIONS" ("ChatSessionId") ON DELETE CASCADE,
    CONSTRAINT "CK_ChatMessages_Sender" CHECK ("SenderType" IN ('Visitor', 'Bot', 'Staff'))
);

CREATE INDEX "IX_ChatMessages_ChatSessionId"
    ON public."CHAT_MESSAGES" ("ChatSessionId");

