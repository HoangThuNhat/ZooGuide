-- Geofencing verification. Fixed the original SQL Server typo:
-- @UserLon was 10.705100 but should be 106.705100.
WITH user_position AS (
    SELECT 10.787500::double precision AS lat, 106.705100::double precision AS lon
),
area_distance AS (
    SELECT
        ar."AreaId",
        ar."Name" AS "AreaName",
        ar."RadiusMeters",
        6371000.0 * 2.0 * ASIN(SQRT(
            POWER(SIN(RADIANS(ar."Latitude"::double precision - up.lat) / 2.0), 2.0) +
            COS(RADIANS(up.lat)) * COS(RADIANS(ar."Latitude"::double precision)) *
            POWER(SIN(RADIANS(ar."Longitude"::double precision - up.lon) / 2.0), 2.0)
        )) AS "DistanceToVisitorMeters"
    FROM public."AREAS" ar
    CROSS JOIN user_position up
)
SELECT
    "AreaId",
    "AreaName",
    "RadiusMeters",
    ROUND("DistanceToVisitorMeters"::numeric, 2) AS "DistanceToVisitorMeters",
    CASE
        WHEN "DistanceToVisitorMeters" <= "RadiusMeters" THEN 'ĐANG Ở TRONG KHU VỰC'
        ELSE 'NGOÀI KHU VỰC'
    END AS "GeofenceStatus"
FROM area_distance
ORDER BY "AreaId";

