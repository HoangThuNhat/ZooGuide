-- =============================================================================
-- ZooGuide Non-Destructive Schema Migration for Supabase PostgreSQL
-- Purpose:
--   1. Extend LANGUAGES with native name, locale, TTS voice, flag icon, display order.
--   2. Create CONTENT_TRANSLATIONS table with unique composite constraint
--      (EntityType, EntityId, EntityKey, LanguageCode) for UI, Area, Enclosure,
--      Species, Animal, and TicketType translations across 12+ languages.
--   3. Extend AUDIOS with Supabase Storage metadata (StorageBucket, ObjectPath,
--      PublicUrl, LanguageCode, VoiceName, TtsProvider, Sha256Hash, IsVerified).
--   4. Extend SPECIES, AREAS, ENCLOSURES, NARRATIONS, ANIMALS with grounded
--      reference source metadata and real veterinary health fields.
--   5. Ensure Supabase Storage bucket 'narration-audio' and read policy exist.
-- =============================================================================

BEGIN;

-- 1. Extend LANGUAGES
ALTER TABLE "LANGUAGES" ADD COLUMN IF NOT EXISTS "NativeName" character varying(100);
ALTER TABLE "LANGUAGES" ADD COLUMN IF NOT EXISTS "Locale" character varying(20);
ALTER TABLE "LANGUAGES" ADD COLUMN IF NOT EXISTS "FlagIcon" character varying(20);
ALTER TABLE "LANGUAGES" ADD COLUMN IF NOT EXISTS "TtsVoice" character varying(100);
ALTER TABLE "LANGUAGES" ADD COLUMN IF NOT EXISTS "DisplayOrder" integer NOT NULL DEFAULT 0;

-- 2. Create CONTENT_TRANSLATIONS
CREATE TABLE IF NOT EXISTS "CONTENT_TRANSLATIONS" (
    "TranslationId" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "EntityType" character varying(50) NOT NULL,
    "EntityId" integer NOT NULL DEFAULT 0,
    "EntityKey" character varying(100) NOT NULL DEFAULT '',
    "LanguageCode" character varying(10) NOT NULL,
    "Title" character varying(300),
    "Summary" character varying(1000),
    "Description" text,
    "ExtraJson" text,
    "TranslationStatus" character varying(20) NOT NULL DEFAULT 'Published',
    "IsPublished" boolean NOT NULL DEFAULT true,
    "SourceReference" character varying(500),
    "CreatedAt" timestamp with time zone NOT NULL DEFAULT now(),
    "UpdatedAt" timestamp with time zone
);

CREATE UNIQUE INDEX IF NOT EXISTS "UQ_ContentTranslations_Entity_Lang"
    ON "CONTENT_TRANSLATIONS" ("EntityType", "EntityId", "EntityKey", "LanguageCode");

CREATE INDEX IF NOT EXISTS "IX_ContentTranslations_Lang_Type"
    ON "CONTENT_TRANSLATIONS" ("LanguageCode", "EntityType");

-- 3. Extend AUDIOS
ALTER TABLE "AUDIOS" ADD COLUMN IF NOT EXISTS "StorageBucket" character varying(100) DEFAULT 'narration-audio';
ALTER TABLE "AUDIOS" ADD COLUMN IF NOT EXISTS "ObjectPath" character varying(500);
ALTER TABLE "AUDIOS" ADD COLUMN IF NOT EXISTS "PublicUrl" character varying(500);
ALTER TABLE "AUDIOS" ADD COLUMN IF NOT EXISTS "LanguageCode" character varying(10);
ALTER TABLE "AUDIOS" ADD COLUMN IF NOT EXISTS "VoiceName" character varying(100);
ALTER TABLE "AUDIOS" ADD COLUMN IF NOT EXISTS "TtsProvider" character varying(50);
ALTER TABLE "AUDIOS" ADD COLUMN IF NOT EXISTS "Sha256Hash" character varying(64);
ALTER TABLE "AUDIOS" ADD COLUMN IF NOT EXISTS "IsVerified" boolean NOT NULL DEFAULT false;

-- 4. Extend NARRATIONS
ALTER TABLE "NARRATIONS" ADD COLUMN IF NOT EXISTS "ReferenceSource" character varying(500);

-- 5. Extend SPECIES
ALTER TABLE "SPECIES" ADD COLUMN IF NOT EXISTS "Habitat" character varying(300);
ALTER TABLE "SPECIES" ADD COLUMN IF NOT EXISTS "Diet" character varying(300);
ALTER TABLE "SPECIES" ADD COLUMN IF NOT EXISTS "Lifespan" character varying(100);
ALTER TABLE "SPECIES" ADD COLUMN IF NOT EXISTS "ReferenceSource" character varying(500);

-- 6. Extend AREAS & ENCLOSURES
ALTER TABLE "AREAS" ADD COLUMN IF NOT EXISTS "ReferenceSource" character varying(500);
ALTER TABLE "ENCLOSURES" ADD COLUMN IF NOT EXISTS "ReferenceSource" character varying(500);

-- 7. Extend ANIMALS with real veterinary health check fields & reference source
ALTER TABLE "ANIMALS" ADD COLUMN IF NOT EXISTS "WeightKg" numeric(8,2);
ALTER TABLE "ANIMALS" ADD COLUMN IF NOT EXISTS "TemperatureC" numeric(5,2);
ALTER TABLE "ANIMALS" ADD COLUMN IF NOT EXISTS "VeterinarianName" character varying(150);
ALTER TABLE "ANIMALS" ADD COLUMN IF NOT EXISTS "HealthActionRequired" character varying(500);
ALTER TABLE "ANIMALS" ADD COLUMN IF NOT EXISTS "LastHealthCheckAt" timestamp with time zone;
ALTER TABLE "ANIMALS" ADD COLUMN IF NOT EXISTS "ReferenceSource" character varying(500);

-- 8. Ensure Supabase Storage bucket 'narration-audio' exists
INSERT INTO storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
VALUES (
    'narration-audio',
    'narration-audio',
    true,
    26214400,
    ARRAY['audio/mpeg', 'audio/mp3', 'audio/wav', 'audio/ogg', 'audio/mp4', 'audio/aac']
)
ON CONFLICT (id) DO UPDATE SET
    public = EXCLUDED.public,
    file_size_limit = EXCLUDED.file_size_limit,
    allowed_mime_types = EXCLUDED.allowed_mime_types;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_policies
        WHERE schemaname = 'storage' AND tablename = 'objects' AND policyname = 'Public Read Narration Audio'
    ) THEN
        CREATE POLICY "Public Read Narration Audio"
            ON storage.objects FOR SELECT
            USING (bucket_id = 'narration-audio');
    END IF;
END
$$;

COMMIT;
